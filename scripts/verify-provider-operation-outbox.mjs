import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read = path => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8');
const schema = read('server/db/schema.ts');
const finance = read('server/routes/finance.ts');
const migration = read('server/db/migrations/0015_provider_operation_outbox.sql');
assert.match(schema, /export const providerOperationOutbox = pgTable\("provider_operation_outbox"/);
for (const field of ['operationType', 'resourceId', 'idempotencyKey', 'status', 'requestedBy', 'attemptCount', 'providerReference', 'httpStatus', 'dispatchStartedAt', 'resolvedAt']) assert.ok(schema.includes(`${field}:`), `schema field ${field}`);
assert.match(migration, /idempotency_key varchar\(120\) NOT NULL UNIQUE/);
assert.match(migration, /CHECK \(operation_type IN \('refund','payout'\)\)/);
assert.match(migration, /CHECK \(status IN \('reserved','dispatching','accepted','rejected','unknown','reconciled'\)\)/);
assert.match(finance, /INSERT INTO provider_operation_outbox\(operation_type,resource_id,idempotency_key,requested_by,status\)/);
assert.match(finance, /operationType: "refund"[\s\S]{0,220}status: "reserved"/);
assert.ok(finance.includes('action: "finance.refund_submission_reserved"'));
assert.ok(finance.includes('finance.payout_submission_reserved'));
assert.match(finance, /status: "dispatching", attemptCount: sql`\$\{providerOperationOutbox\.attemptCount\} \+ 1`/);
assert.match(finance, /WHERE idempotency_key=\$1 AND status='reserved'/);
assert.match(finance, /provider-operations\/attention/);
assert.match(finance, /automaticRetry: false/);
assert.ok(finance.includes("no retry is initiated here"));
assert.match(finance, /status: parsed\.data\.outcome === "unknown" \? "unknown" : "reconciled"/);
const queueStart = finance.indexOf('financeRouter.get("/provider-operations/attention"');
const queueEnd = finance.indexOf('\n});', queueStart);
const queue = finance.slice(queueStart, queueEnd);
for (const forbidden of ['destinationCiphertext', 'payerPhoneCiphertext', 'destination_ciphertext', 'payer_phone']) assert.ok(!queue.includes(forbidden), `queue must not expose ${forbidden}`);
assert.ok(queue.includes('requireRole("admin", "owner")'));
console.log('Provider-operation outbox source guard passed: refund/payout reservations, unique idempotency, attention queue privacy, and no automatic retry.');
