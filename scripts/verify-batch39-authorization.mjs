import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read = path => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8');
const roles = read('shared/admin-role-policy.mjs');
const security = read('server/security.ts');
const docs = read('server/routes/agent-documents.ts');
const admin = read('server/routes/admin.ts');
assert.match(roles, /legacyAdminScopes/);
assert.match(roles, /ownerHasFinalAuthority/);
assert.match(security, /normalizePrivilegedRoles\(roles\.map\(row => row\.role\)\)/);
assert.match(security, /hasRoleAuthority\(req\.auth\.roles, allowed\)/);
assert.match(docs, /agentDocumentsRouter\.get\("\/me"[\s\S]*?eq\(agents\.userId, req\.auth!\.id\)/);
assert.match(docs, /agentDocumentsRouter\.get\("\/admin\/:agentId", requireRole\("admin"\)/);
assert.match(docs, /eq\(documents\.resourceId, agent\.id\)/);
assert.match(docs, /agentDocumentsRouter\.patch\("\/admin\/:agentId\/:documentId\/review", requireRole\("admin"\)/);
assert.match(docs, /eq\(documents\.id, req\.params\.documentId\), eq\(documents\.resourceId, req\.params\.agentId\)/);
assert.match(docs, /agentDocumentsRouter\.delete\("\/admin\/:agentId\/:documentId", requireRole\("admin"\)/);
assert.match(docs, /storage keys are never exposed/);
assert.match(admin, /adminRouter\.get\("\/overview", requireRole\("admin", "owner"\)/);
assert.match(admin, /adminRouter\.get\("\/audit-events", requireRole\("admin", "owner"\)/);
console.log('Batch 39 authorization guard passed: canonical two-role authority, owner final authority, self-scoped document reads, agent/document compound scoping, and privacy-minimized Admin queues.');
