import { readFile } from "node:fs/promises";
import assert from "node:assert/strict";
const admin = await readFile(new URL("../server/routes/admin.ts", import.meta.url), "utf8");
const finance = await readFile(new URL("../server/routes/finance.ts", import.meta.url), "utf8");
const roleScript = await readFile(new URL("./grant-role.ts", import.meta.url), "utf8");
const policy = await readFile(new URL("../shared/admin-bootstrap-policy.mjs", import.meta.url), "utf8");
const demo = await readFile(new URL("../src/demo/data.ts", import.meta.url), "utf8");
const app = await readFile(new URL("../src/App.tsx", import.meta.url), "utf8");
const demoUi = await readFile(new URL("../src/components/DemoExperience.tsx", import.meta.url), "utf8");
assert.match(finance, /const financeAccess = hasAdminAuthority\(req\.auth!\.roles\)/);
assert.match(roleScript, /OWNER_BOOTSTRAP_EMAIL/);
assert.doesNotMatch(roleScript, /roleArg === "admin"/);
assert.match(roleScript, /Admin roles are granted only by the Super Admin in the authenticated workspace/);
assert.match(roleScript, /OWNER_BOOTSTRAP_EMAIL/);
assert.match(roleScript, /admin\.owner_bootstrapped/);
assert.match(roleScript, /supersededAdminScopes/);
assert.match(policy, /activeOwnerCount === 0/);
assert.doesNotMatch(policy, /canGrantAdmin/);
assert.doesNotMatch(demo, /role: "(?:finance|trust_safety|communications_writer|communications_approver|communications_publisher|support)"/);
assert.doesNotMatch(demoUi, /role === "(?:finance|trust_safety|support)"|role\.startsWith\("communications_"\)/);
assert.match(admin, /adminRouter\.get\("\/users", requireRole\("owner"\)/);
assert.match(admin, /adminRouter\.post\("\/users\/:userId\/admin-role", requireRole\("owner"\)/);
assert.match(admin, /adminRouter\.delete\("\/users\/:userId\/admin-role", requireRole\("owner"\)/);
assert.match(admin, /sessionsRevoked: true/);
assert.match(app, /OwnerAdminRolePanel/);
console.log("Two-role demo, finance authorization and Owner-approved role provisioning guards passed.");
